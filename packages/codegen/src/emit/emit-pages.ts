import { mkdir, writeFile } from 'node:fs/promises';
import { join, relative } from 'node:path';
import type { DiscoveredPage } from '../discovery/pages.js';

export interface EmitPagesOptions {
  /** The export name to reference in import() type expressions (default: 'ComponentProps'). */
  propsExport?: string;
}

export async function emitPages(
  pages: DiscoveredPage[],
  outDir: string,
  options: EmitPagesOptions = {},
): Promise<void> {
  const propsExport = options.propsExport ?? 'ComponentProps';
  await mkdir(outDir, { recursive: true });
  const body = pages
    .map((p) => {
      const propType = p.propsSource ?? 'unknown';
      // Use JSON.stringify for the key so unsafe chars (quotes, backslashes, etc.)
      // are properly escaped. Strip the surrounding double-quotes for TypeScript
      // interface key syntax (TS accepts both 'key' and "key" — we use double).
      const key = needsQuotes(p.name) ? JSON.stringify(p.name) : p.name;
      return `  ${key}: ${propType};`;
    })
    .join('\n');

  // Build InertiaPageName union type
  const pageNameUnion =
    pages.length > 0
      ? pages.map((p) => JSON.stringify(p.name)).join(' | ')
      : 'never';

  // Build module augmentation entries (page name -> import('...').ComponentProps or Record<string, unknown>)
  const augBody = pages
    .map((p) => {
      const key = needsQuotes(p.name) ? JSON.stringify(p.name) : p.name;
      const valueType = buildAugmentationType(p, outDir, propsExport);
      return `    ${key}: ${valueType};`;
    })
    .join('\n');

  // Build InertiaProps helper type
  const propsHelper =
    '\nexport type InertiaProps<K extends InertiaPageName> = import(\'@dudousxd/nestjs-inertia\').InertiaPages[K];\n';

  const content =
    `// Generated by @dudousxd/nestjs-inertia-codegen. Do not edit.\nexport interface InertiaPages {\n${body}\n}\n` +
    `\nexport type InertiaPageName = ${pageNameUnion};\n` +
    propsHelper +
    `\ndeclare module '@dudousxd/nestjs-inertia' {\n  interface InertiaPages {\n${augBody}\n  }\n}\n`;

  await writeFile(join(outDir, 'pages.d.ts'), content, 'utf8');
}

/**
 * Build the type for a page in the module augmentation.
 * Pages with propsSource get `import('...').ComponentProps`;
 * pages without get `Record<string, unknown>`.
 */
function buildAugmentationType(
  page: DiscoveredPage,
  outDir: string,
  propsExport: string,
): string {
  if (!page.propsSource) {
    return 'Record<string, unknown>';
  }
  // Compute the import path: relative from outDir to the page's absolute path, without extension
  let importPath = relative(outDir, page.absolutePath)
    .replace(/\.(tsx?|vue|svelte)$/, '');
  // Ensure it starts with './' for a relative import
  if (!importPath.startsWith('.')) {
    importPath = `./${importPath}`;
  }
  return `import('${importPath}').${propsExport}`;
}

function needsQuotes(name: string): boolean {
  return !/^[A-Za-z_$][A-Za-z0-9_$]*$/.test(name);
}
